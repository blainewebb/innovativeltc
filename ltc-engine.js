function ageRow(table, age){
  if (age <= 40) return table["18-40"];
  if (table[String(age)]) return table[String(age)];
  throw new Error("Issue age " + age + " is outside NGL's rated range (18–79).");
}
function pickTable(state, worksite){
  if (state && state.toUpperCase() === "CO") return "CO Non-Worksite";
  if (worksite) return "Generic Worksite";
  return "Generic Non-Worksite";
}
const MODE_ANNUALIZER = {annual:1, semiannual:2, quarterly:4, monthly:12};

function quote(o){
  const f = RATES.factors;
  const tname = pickTable(o.state, o.worksite);
  const table = RATES.tables[tname];
  const row = ageRow(table, o.age);
  let pop;
  if (o.joint) pop = "joint";
  else if (tname === "Generic Non-Worksite") pop = (o.gender||"female").toLowerCase();
  else pop = "single";
  const base = row.base[pop];
  if (base == null) throw new Error("No base rate for '"+pop+"' in "+tname+".");
  const bp = String(o.benefitPeriod || "36");
  const ep = String(o.elimination || "90");
  const mode = o.mode || "monthly";
  const pay = o.pay || "level";
  const units = o.monthlyBenefit / RATES.base_unit;
  let annual = base * units;
  const steps = [["base "+base+" × "+units+" units ($"+Math.round(o.monthlyBenefit).toLocaleString()+"/mo ÷ $300)", annual]];
  if (o.inflation){
    const cf = row.cola[String(o.inflation)];
    if (cf == null) throw new Error("Unsupported inflation option "+o.inflation);
    annual *= cf; steps.push(["× "+cf+" compound COLA @ "+(o.inflation*100)+"%", annual]);
  }
  const bpf = f.benefit_period[bp]; if (bpf==null) throw new Error("Bad benefit period "+bp);
  annual *= bpf; steps.push(["× "+bpf+" benefit period ("+bp+"-mo)", annual]);
  const epf = f.elimination_period[ep]; if (epf==null) throw new Error("Bad elimination "+ep);
  annual *= epf; steps.push(["× "+epf+" elimination ("+ep+"-day)", annual]);
  const rcf = f.risk_class[o.riskClass||"Premier"] ?? 1.0;
  annual *= rcf; if (rcf!==1.0) steps.push(["× "+rcf+" risk class", annual]);
  if (o.classOne){ annual *= 1.35; steps.push(["× 1.35 Class One (substandard)", annual]); }
  if (o.riderSharedAdditional){
    const tbp = String(o.totalBenefitPeriod || bp);
    const sba = f.rider_shared_additional_by_total_bp[tbp];
    if (sba==null) throw new Error("Shared Additional rider needs valid total benefit period.");
    annual *= sba; steps.push(["× "+sba+" Shared Additional rider (total "+tbp+"-mo)", annual]);
  }
  if (o.riderFirstDayHccs){ annual *= f.rider_first_day_hccs; steps.push(["× "+f.rider_first_day_hccs+" First-Day HCCS rider", annual]); }
  if (o.riderShortenedBenefit){ annual *= f.rider_shortened_benefit_period; steps.push(["× "+f.rider_shortened_benefit_period+" Shortened Benefit rider", annual]); }
  const res = {table:tname, population:pop, steps:steps};
  if (pay === "single"){
    const sp = row.singlepay; const single = annual*sp;
    steps.push(["× "+sp+" Single-Pay factor", single]);
    res.pay="Single-Pay"; res.singlePremium=Math.round(single*100)/100; return res;
  }
  let annualPremium = annual; res.pay = "Level";
  if (pay === "10pay"){ const tp=row.tenpay; annualPremium=annual*tp; steps.push(["× "+tp+" 10-Pay factor", annualPremium]); res.pay="10-Pay"; }
  const mf = f.payment_mode[mode]; if (mf==null) throw new Error("Bad mode "+mode);
  res.annualPremium = Math.round(annualPremium*100)/100;
  res.mode = mode;
  res.modalPayment = Math.round(annualPremium*mf*100)/100;
  return res;
}

function quoteCouple(a1,g1,a2,g2,monthlyBenefit,opts){
  opts = opts||{};
  let older,oldg,yng,yngg;
  if (a1>=a2){older=a1;oldg=g1;yng=a2;yngg=g2;} else {older=a2;oldg=g2;yng=a1;yngg=g1;}
  const combined = quote(Object.assign({}, opts, {age:older, gender:oldg, monthlyBenefit, joint:true}));
  const survOlder = quote(Object.assign({}, opts, {age:older, gender:oldg, monthlyBenefit}));
  const survYng = quote(Object.assign({}, opts, {age:yng, gender:yngg, monthlyBenefit}));
  const out = {combined_joint:combined};
  out["survivor_"+oldg] = survOlder; out["survivor_"+yngg] = survYng;
  return out;
}

function benefitForPremium(target, age, gender, opts){
  opts = opts||{};
  const ref = quote(Object.assign({}, opts, {age, gender, monthlyBenefit:RATES.base_unit}));
  const refCost = ref.singlePremium != null ? ref.singlePremium : ref.modalPayment;
  const monthlyBenefit = RATES.base_unit * (target/refCost);
  const full = quote(Object.assign({}, opts, {age, gender, monthlyBenefit}));
  return {targetPremium:target, solvedMonthlyBenefit:Math.round(monthlyBenefit*100)/100, quote:full};
}

function runScenario(scenario, age, gender, opts){
  opts = opts||{};
  return scenario.options.map(op=>{
    const cfg = {age, gender, monthlyBenefit:op.monthly_benefit,
      benefitPeriod:op.benefit_period, elimination:op.elimination, inflation:op.inflation};
    const q = quote(Object.assign({}, opts, cfg));
    return {option:op.name, monthlyBenefit:op.monthly_benefit, benefitPeriod:op.benefit_period,
      inflation:op.inflation, monthlyPremium:q.modalPayment, annualPremium:q.annualPremium};
  });
}

